initial_state = {"AT_A"}
goal = "AT_C"

actions = [
    {
        "name": "move A to B",
        "per": {"AT_A"},
        "add": {"AT_B"},
        "delete": {"AT_A"}
    },
    {
        "name": "move B to C",
        "per": {"AT_B"},
        "add": {"AT_C"},
        "delete": {"AT_B"}

    }
]

def find_actions(goal):
    for action in actions:
        if goal in action["add"]:
            return action
    return None

def make_plan(goal,state,plan):
  #goal is already true
  if goal in state:
      return True
  #find an action that can achieve the goal
  action = find_actions(goal)
  if action is None:
      return False
  #first achieve the action's preconditions
  for condition in action ["per"]:
      if not make_plan(condition, state, plan):
          return False
  #perform the action
  state.difference_update(action["delete"])
  state.update(action["add"])
  plan.append(action["name"])
  return True

state = initial_state.copy()
plan = []

make_plan(goal,state,plan)

print("plan:")
for step in plan:
    print(step)
